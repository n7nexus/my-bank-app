#!/bin/bash

set -e
set -u

echo 'Start'

psql -v ON_ERROR_STOP=1 <<-EOSQL
CREATE USER $BANK_POSTGRES_USER WITH
    LOGIN
    SUPERUSER
    INHERIT
    CREATEDB
    CREATEROLE
    NOREPLICATION
    ENCRYPTED PASSWORD '$BANK_POSTGRES_PASSWORD';

CREATE DATABASE $BANK_POSTGRES_DB
    WITH
    OWNER = $BANK_POSTGRES_USER
    ENCODING = 'UTF8'
    LC_COLLATE = 'en_US.UTF-8'
    LC_CTYPE = 'en_US.UTF-8'
    TABLESPACE = pg_default
    CONNECTION LIMIT = -1
    TEMPLATE = template0;

\connect $BANK_POSTGRES_DB;

CREATE SCHEMA IF NOT EXISTS $ACCOUNT_POSTGRES_DB_SCHEMA AUTHORIZATION $BANK_POSTGRES_USER;
CREATE SCHEMA IF NOT EXISTS $TRANSFER_POSTGRES_DB_SCHEMA AUTHORIZATION $BANK_POSTGRES_USER;
CREATE SCHEMA IF NOT EXISTS $CASH_POSTGRES_DB_SCHEMA AUTHORIZATION $BANK_POSTGRES_USER;
CREATE SCHEMA IF NOT EXISTS liquibase AUTHORIZATION $BANK_POSTGRES_USER;

EOSQL

echo 'DONE'
